#!/usr/bin/env bash
# install.sh -- install wtb2kwant into a conda environment that provides Kwant.
#
# Usage:
#   ./install.sh                 # install into the conda env "kwant" (created if missing)
#   ./install.sh --env myenv     # use/create another environment name
#   ./install.sh --no-editable   # regular install instead of editable (pip -e)
#   ./install.sh --dev           # also install pytest (to run the test suite)
#   ./install.sh --help
#
# Requirements: conda (Anaconda/Miniconda/Miniforge) available in PATH, or
# mamba. New environments are created from conda-forge.
set -euo pipefail

ENV_NAME="kwant"
EDITABLE=1
DEV=0
PYTHON_VERSION="3.12"

usage() { sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'; }

while [[ $# -gt 0 ]]; do
    case "$1" in
        --env)          ENV_NAME="$2"; shift 2 ;;
        --env=*)        ENV_NAME="${1#*=}"; shift ;;
        --no-editable)  EDITABLE=0; shift ;;
        --dev)          DEV=1; shift ;;
        --python)       PYTHON_VERSION="$2"; shift 2 ;;
        -h|--help)      usage; exit 0 ;;
        *) echo "Unknown option: $1" >&2; usage; exit 1 ;;
    esac
done

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# ---------------------------------------------------------------- conda
if command -v mamba >/dev/null 2>&1; then
    SOLVER=mamba
elif command -v conda >/dev/null 2>&1; then
    SOLVER=conda
else
    echo "ERROR: conda (or mamba) not found in PATH." >&2
    echo "Install Miniforge (https://github.com/conda-forge/miniforge) and try again." >&2
    exit 1
fi
CONDA=conda
command -v conda >/dev/null 2>&1 || CONDA=mamba

env_exists() {
    "$CONDA" env list | awk '!/^#/ && NF {print $1}' | grep -Fxq "$ENV_NAME"
}

echo "==> wtb2kwant installer"
echo "    repository : $REPO_DIR"
echo "    conda env  : $ENV_NAME"

if env_exists; then
    echo "==> Environment '$ENV_NAME' found."
else
    echo "==> Environment '$ENV_NAME' not found: creating it (conda-forge, python=$PYTHON_VERSION)..."
    "$SOLVER" create -y -n "$ENV_NAME" -c conda-forge \
        "python=$PYTHON_VERSION" kwant numpy matplotlib
fi

run_in_env() { "$CONDA" run --no-capture-output -n "$ENV_NAME" "$@"; }

# Make sure Kwant and the plotting stack are importable; install what is missing.
if ! run_in_env python -c "import kwant" >/dev/null 2>&1; then
    echo "==> Kwant not importable in '$ENV_NAME': installing from conda-forge..."
    "$SOLVER" install -y -n "$ENV_NAME" -c conda-forge kwant
fi
if ! run_in_env python -c "import matplotlib" >/dev/null 2>&1; then
    echo "==> Installing matplotlib..."
    "$SOLVER" install -y -n "$ENV_NAME" -c conda-forge matplotlib
fi
if [[ $DEV -eq 1 ]] && ! run_in_env python -c "import pytest" >/dev/null 2>&1; then
    echo "==> Installing pytest..."
    "$SOLVER" install -y -n "$ENV_NAME" -c conda-forge pytest
fi

# ---------------------------------------------------------------- package
echo "==> Installing wtb2kwant into '$ENV_NAME'..."
if [[ $EDITABLE -eq 1 ]]; then
    run_in_env python -m pip install --no-deps -e "$REPO_DIR"
else
    run_in_env python -m pip install --no-deps "$REPO_DIR"
fi

# ---------------------------------------------------------------- bin/
# Launchers that call the environment's Python directly: put <repo>/bin in PATH
# and use the tool without activating conda.
ENV_PY="$(run_in_env python -c 'import sys; print(sys.executable)')"
BIN_DIR="$REPO_DIR/bin"
mkdir -p "$BIN_DIR"
echo "==> Writing launchers to $BIN_DIR (python: $ENV_PY)"

cat > "$BIN_DIR/wtb2kwant" <<EOF
#!/usr/bin/env bash
# wtb2kwant launcher generated by install.sh -- do not edit (rerun install.sh)
# conda env: $ENV_NAME
exec "$ENV_PY" -m wtb2kwant.cli "\$@"
EOF

cat > "$BIN_DIR/wtb2kwant-python" <<EOF
#!/usr/bin/env bash
# Python of the conda env "$ENV_NAME" (with kwant + wtb2kwant), generated by install.sh.
# Use it to run generated scripts:  wtb2kwant-python kwant_model.py --help
exec "$ENV_PY" "\$@"
EOF
chmod +x "$BIN_DIR/wtb2kwant" "$BIN_DIR/wtb2kwant-python"

# ---------------------------------------------------------------- check
echo "==> Checking installation..."
run_in_env python -c "import kwant, wtb2kwant; print('    kwant', kwant.__version__, '| wtb2kwant', wtb2kwant.__version__)"
run_in_env wtb2kwant --help >/dev/null && echo "    command 'wtb2kwant' (conda env) OK"
"$BIN_DIR/wtb2kwant" --help >/dev/null && echo "    launcher bin/wtb2kwant OK"
"$BIN_DIR/wtb2kwant-python" -c "import kwant, wtb2kwant" && echo "    launcher bin/wtb2kwant-python OK"

cat <<EOF

Done. Either activate the environment:
    conda activate $ENV_NAME
    wtb2kwant tb_hr.dat --wout wannier90.wout -o kwant_model.py
    python kwant_model.py --help

or use the launchers in $BIN_DIR (no activation needed):
    export PATH="$BIN_DIR:\$PATH"      # e.g. in ~/.bashrc
    wtb2kwant tb_hr.dat --wout wannier90.wout -o kwant_model.py
    wtb2kwant-python kwant_model.py --help
EOF
